import test from 'tape'
import parsePage from '../lib.ts'

test('HTML renders standard Markdown and respects heading modes', (t) => {
  const page = parsePage('## Foo\n\nHello **bold**, *italic*, ~~gone~~ and `code`.')
  const html = page.html()
  t.ok(html.includes('<h2>Foo</h2>'))
  t.ok(html.includes('<strong>bold</strong>'))
  t.ok(html.includes('<em>italic</em>'))
  t.ok(html.includes('<del>gone</del>'))
  t.ok(html.includes('<code>code</code>'))
  t.equal(page.headings()[0].html(), '<h2>Foo</h2>')
  t.equal(page.headings()[0].html({ headings: 'inline' }), 'Foo')
  t.equal(page.headings()[0].html({ headings: false }), '')
  t.notOk(page.html({ headings: false }).includes('Foo'))
  t.notOk(page.html({ headings: 'inline' }).includes('<h2>'))
  t.equal(page.headings()[0].text(), 'Foo', 'HTML does not mutate text output')
  t.end()
})

test('HTML renders lists, tables, blockquotes, code, and references', (t) => {
  const page = parsePage('- [x] Done\n- [ ] Todo\n\n> Quote\n\n| A | B |\n| - | - |\n| 1 | 2 |\n\n```js\nconst x = "<"\n```\n\n[Link][ref]\n\n[ref]: https://example.com "Title"')
  const html = page.html()
  t.ok(html.includes('<ul'))
  t.ok(html.includes('type="checkbox"'))
  t.ok(html.includes('checked'))
  t.ok(html.includes('<blockquote>'))
  t.ok(html.includes('<table>'))
  t.ok(html.includes('<th>A</th>'))
  t.ok(html.includes('language-js'))
  t.notOk(html.includes('const x = "<"'), 'code content is escaped')
  t.ok(page.links()[0].html().includes('href="https://example.com"'), 'section resolves page references')
  t.ok(page.links()[0].html().includes('title="Title"'))
  t.end()
})

test('HTML supports Obsidian links, embeds, highlights, tags, and callouts', (t) => {
  const page = parsePage('[[My Note|Label]] ![[photo.jpg|500]] ==Marked== #tag\n\n> [!tip]- Title\n> Body [[Note]]')
  const html = page.html()
  t.ok(html.includes('href="My%20Note"'))
  t.ok(html.includes('>Label</a>'))
  t.ok(html.includes('<img'))
  t.ok(html.includes('src="photo.jpg"'))
  t.ok(html.includes('width="500"'))
  t.ok(html.includes('<mark>Marked</mark>'))
  t.ok(html.includes('#tag'))
  t.ok(html.includes('<details'))
  t.notOk(html.includes(' open'), 'collapsed callout starts closed')
  t.ok(html.includes('<summary'))
  t.ok(html.includes('Title'))
  t.notOk(page.html({ callouts: false }).includes('Body'))
  t.notOk(page.callouts()[0].html({ callouts: 'body' }).includes('Title'))
  t.ok(page.callouts()[0].html({ callouts: 'body' }).includes('Body'))
  page.links()[0].title = 'Changed'
  t.ok(page.html().includes('>Changed</a>'), 'HTML reflects live edits')
  t.end()
})

test('HTML escapes text and raw markup and rejects unsafe URLs', (t) => {
  const page = parsePage('Text <b>bold</b>\n\n<script>alert(1)</script>\n\n<img src="x" onerror="alert(1)">\n\n[bad](javascript:alert%281%29)')
  const html = page.html()
  t.ok(html.includes('&lt;b&gt;bold&lt;/b&gt;'), 'raw HTML is displayed literally')
  t.notOk(html.includes('<script'))
  t.notOk(html.includes('<img src="x"'), 'raw attributes cannot create an element')
  t.notOk(html.includes('javascript:'))
  t.notOk(page.html({ html: false }).includes('<b>'))
  const link = parsePage('[[Note]]').links()[0]
  link.title = '<img src=x onerror=alert(1)>'
  t.notOk(link.html().includes('<img'), 'edited labels stay literal')
  t.end()
})

test('HTML handles footnotes and keeps renderer source available for math and Mermaid', (t) => {
  const page = parsePage('Footnote[^one] and ^[inline note].\n\n[^one]: Definition\n\n$x^2$\n\n```mermaid\ngraph TD; A-->B\n```')
  const html = page.html()
  t.ok(html.includes('Definition'))
  t.ok(html.includes('inline note'))
  t.ok(html.includes('data-footnote-ref'))
  t.ok(html.includes('language-math'))
  t.ok(html.includes('language-mermaid'))
  t.ok(page.paragraphs()[0].html().includes('Definition'), 'section footnotes resolve against the page')
  const definition = page.footnotes().find(note => note.ast().type === 'footnoteDefinition')
  t.ok(definition.html().includes('Definition'), 'a footnote section renders its body directly')
  t.end()
})

test('HTML hides comments and frontmatter by default, with explicit inclusion', (t) => {
  const page = parsePage('---\ntitle: Secret\n---\n\nVisible %%hidden%%')
  t.notOk(page.html().includes('Secret'))
  t.notOk(page.html().includes('hidden'))
  t.ok(page.html({ frontmatter: true }).includes('Secret'))
  t.ok(page.html({ comments: true }).includes('hidden'))
  t.equal(page.comments()[0].html(), '')
  t.equal(page.markdown(), '---\ntitle: Secret\n---\n\nVisible %%hidden%%')
  t.end()
})

test('HTML keeps local heading, block, and footnote anchors connected', (t) => {
  const page = parsePage('[[#Heading]] [[#^block]] Note[^one]\n\n# Heading\n\nParagraph ^block\n\n[^one]: Footnote')
  const html = page.html()
  const ids = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]))
  const anchors = [...html.matchAll(/\shref="#([^"]+)"/g)].map(match => decodeURIComponent(match[1]))
  t.ok(anchors.length >= 4, 'heading, block, footnote, and backlink are present')
  anchors.forEach(anchor => t.ok(ids.has(anchor), `anchor ${anchor} has a destination`))
  t.notOk(page.html({ footnotes: false }).includes('data-footnote-ref'))
  t.notOk(page.html({ blockIds: false }).includes('id="user-content-block-'))
  t.end()
})

test('HTML preserves image dimensions and uses links for note embeds', (t) => {
  const page = parsePage('![Caption|200x100](photo.png) ![[Other Note]]')
  const html = page.html()
  t.ok(html.includes('width="200"'))
  t.ok(html.includes('height="100"'))
  t.ok(html.includes('alt="Caption"'))
  t.ok(html.includes('class="internal-embed"'))
  t.ok(html.includes('href="Other%20Note"'))
  t.end()
})
